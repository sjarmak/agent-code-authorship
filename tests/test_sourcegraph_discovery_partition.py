def timed_out_parent(
    specification: dict,
    family_id: str = "generated_code_disclosure_diffs",
) -> dict:
    family = next(
        family
        for family in specification["query_families"]
        if family["id"] == family_id
    )
    rendered_query = render_query(family, SOURCEGRAPH_NAME, SHA_A)
    document = {
        "result_manifest_version": 3,
        "query_family_id": family["id"],
        "result_type": family["result_type"],
        "canonical_repository_id": "org/repo",
        "sourcegraph_name": SOURCEGRAPH_NAME,
        "cutoff_commit": SHA_A,
        "rendered_query": rendered_query,
        "rendered_query_sha256": hashlib.sha256(rendered_query.encode()).hexdigest(),
        "executed_at": "2026-07-28T00:00:00Z",
        "sourcegraph_result_ids": [],
        "result_count": 0,
        "result_object_count": 0,
        "limit_hit": False,
        "cloning_repositories": [],
        "missing_repositories": [],
        "timed_out_repositories": [SOURCEGRAPH_NAME],
        "valid": False,
        "invalid_reasons": ["timed_out_repositories"],
        "raw_results": [],
        "outcomes_consulted": False,
    }
    document["unit_id"] = discovery_unit_id(document)
    return {
        **document,
        "result_manifest_sha256": result_manifest_sha256(document),
    }


def empty_response() -> dict:
    return {
        "results": [],
        "result_count": 0,
        "limit_hit": False,
        "cloning_repositories": [],
        "missing_repositories": [],
        "timed_out_repositories": [],
    }



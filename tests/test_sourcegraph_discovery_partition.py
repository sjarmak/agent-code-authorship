def test_partition_execution_is_atomic_resumable_and_checksummed(
    tmp_path: Path,
    specification: dict,
):
    parent = timed_out_parent(specification)
    plan = build_partition_plan(specification, [parent])
    calls = []

    def runner(query: str, *_args: str) -> dict:
        calls.append(query)
        return empty_response()

    first = execute_partition_plan(
        plan,
        specification,
        tmp_path,
        source_parents=[parent],
        query_runner=runner,
        clock=lambda: EXECUTED_AT,
    )
    schema_path = (
        Path(__file__).resolve().parents[1]
        / "study/sourcegraph-discovery-partition-execution.schema.json"
    )
    second = execute_partition_plan(
        plan,
        specification,
        tmp_path,
        source_parents=[parent],
        query_runner=runner,
        clock=lambda: EXECUTED_AT,
    )

    assert first["status"] == "complete"
    assert first["valid_parent_count"] == 1
    assert first["partition_execution_sha256"] == partition_execution_sha256(first)
    assert "executed_child_unit_count" not in first
    assert "reused_child_unit_count" not in second
    assert all(
        "reused" not in child
        for parent_summary in second["parents"]
        for child in parent_summary["children"]
    )
    assert len(calls) == 93
    assert (tmp_path / "sourcegraph-discovery-partition-execution.v3.json").is_file()
    assert list(tmp_path.rglob("*.tmp")) == []
    jsonschema.Draft202012Validator(json.loads(schema_path.read_text())).validate(first)
    assert (
        validate_partition_execution(
            first,
            plan,
            specification,
            tmp_path,
            source_parents=[parent],
        )
        == []
    )
    for child in first["parents"][0]["children"]:
        assert (tmp_path / child["shard_path"]).is_file()


def test_partition_execution_runs_independent_children_with_bounded_parallelism(
    tmp_path: Path,
    specification: dict,
):
    parent = timed_out_parent(specification)
    plan = build_partition_plan(specification, [parent])
    release = Event()
    lock = Lock()
    active = 0
    peak = 0

    def runner(*_args: str) -> dict:
        nonlocal active, peak
        with lock:
            active += 1
            peak = max(peak, active)
            if peak == 2:
                release.set()
        assert release.wait(timeout=1)
        with lock:
            active -= 1
        return empty_response()

    execution = execute_partition_plan(
        plan,
        specification,
        tmp_path,
        source_parents=[parent],
        query_runner=runner,
        clock=lambda: EXECUTED_AT,
        max_workers=2,
    )

    assert execution["status"] == "complete"
    assert peak == 2



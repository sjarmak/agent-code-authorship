def test_refined_plan_replaces_only_timed_out_children_with_daily_windows(
    tmp_path: Path,
    specification: dict,
):
    parent = timed_out_parent(specification)
    plan = build_partition_plan(specification, [parent])
    response = empty_response()
    response["timed_out_repositories"] = [SOURCEGRAPH_NAME]
    execution = execute_partition_plan(
        plan,
        specification,
        tmp_path,
        source_parents=[parent],
        query_runner=lambda *_args: response,
        clock=lambda: EXECUTED_AT,
    )

    refined = build_refined_partition_plan(
        specification,
        plan,
        execution,
        tmp_path,
        source_parents=[parent],
    )

    assert refined["strategy"] == "failed_14_day_windows_refined_to_1_day"
    assert refined["refinement_source_plan_sha256"] == plan["partition_plan_sha256"]
    assert (
        refined["refinement_source_execution_sha256"]
        == execution["partition_execution_sha256"]
    )
    assert refined["child_unit_count"] > plan["child_unit_count"]
    assert all(
        "timeout:5m" in child["unit"]["rendered_query"]
        for child in refined["parents"][0]["children"]
    )
    schema_path = (
        Path(__file__).resolve().parents[1]
        / "study/sourcegraph-discovery-partition-plan.schema.json"
    )
    jsonschema.Draft202012Validator(json.loads(schema_path.read_text())).validate(
        refined
    )
    calls = 0
    call_lock = Lock()

    def runner(*_args: str) -> dict:
        nonlocal calls
        with call_lock:
            calls += 1
        return empty_response()

    final = execute_refined_partition_plan(
        refined,
        specification,
        tmp_path,
        source_plan=plan,
        source_execution=execution,
        source_parents=[parent],
        query_runner=runner,
        clock=lambda: EXECUTED_AT,
    )

    assert final["status"] == "complete"
    assert calls == refined["child_unit_count"]
    assert (
        validate_partition_execution(
            final,
            refined,
            specification,
            tmp_path,
            source_parents=[parent],
            expected_plan=refined,
        )
        == []
    )


def test_branch_refinement_replaces_failed_daily_ai_ban_leaf(
    tmp_path: Path,
    specification: dict,
):
    parent = timed_out_parent(specification, "ai_ban_policy_introduction_diffs")
    root_plan = build_partition_plan(specification, [parent])
    timeout = empty_response()
    timeout["timed_out_repositories"] = [SOURCEGRAPH_NAME]
    root_execution = execute_partition_plan(
        root_plan,
        specification,
        tmp_path,
        source_parents=[parent],
        query_runner=lambda *_args: timeout,
        clock=lambda: EXECUTED_AT,
    )
    daily_plan = build_refined_partition_plan(
        specification,
        root_plan,
        root_execution,
        tmp_path,
        source_parents=[parent],
    )

    def daily_runner(query: str, *_args: str) -> dict:
        return timeout if 'after:"2023-01-01"' in query else empty_response()

    daily_execution = execute_refined_partition_plan(
        daily_plan,
        specification,
        tmp_path,
        source_plan=root_plan,
        source_execution=root_execution,
        source_parents=[parent],
        query_runner=daily_runner,
        clock=lambda: EXECUTED_AT,
    )
    branch_plan = build_query_branch_refined_partition_plan(
        specification,
        daily_plan,
        daily_execution,
        tmp_path,
        source_parents=[parent],
        ancestor_plan=root_plan,
        ancestor_execution=root_execution,
    )

    assert (
        branch_plan["strategy"]
        == "failed_daily_ai_ban_windows_refined_by_filename_policy_and_term"
    )
    failed_daily_children = sum(
        not child["valid"]
        for parent_summary in daily_execution["parents"]
        for child in parent_summary["children"]
    )
    assert (
        branch_plan["child_unit_count"]
        == daily_plan["child_unit_count"] + 125 * failed_daily_children
    )
    assert any(
        "file:(^|/)README(\\.[^/]*)?$" in child["unit"]["rendered_query"]
        and "AI.{0,240}prohibit" in child["unit"]["rendered_query"]
        for parent_plan in branch_plan["parents"]
        for child in parent_plan["children"]
    )
    final = execute_query_branch_refined_partition_plan(
        branch_plan,
        specification,
        tmp_path,
        source_plan=daily_plan,
        source_execution=daily_execution,
        source_parents=[parent],
        ancestor_plan=root_plan,
        ancestor_execution=root_execution,
        query_runner=lambda *_args: empty_response(),
        clock=lambda: EXECUTED_AT,
    )
    assert final["status"] == "complete"
    assert (
        validate_partition_execution(
            final,
            branch_plan,
            specification,
            tmp_path,
            source_parents=[parent],
            expected_plan=branch_plan,
        )
        == []
    )



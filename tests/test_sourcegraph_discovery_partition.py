    parent = timed_out_parent(specification)
    plan = build_partition_plan(specification, [parent])
    execution = execute_partition_plan(
        plan,
        specification,
        tmp_path,
        source_parents=[parent],
        query_runner=lambda *_args: empty_response(),
        clock=lambda: EXECUTED_AT,
    )
    shard_path = tmp_path / execution["parents"][0]["children"][0]["shard_path"]
    outside = tmp_path.parent / "outside-partition-shard.json"
    outside.write_bytes(shard_path.read_bytes())
    shard_path.unlink()
    os.symlink(outside, shard_path)

    errors = validate_partition_execution(
        execution,
        plan,
        specification,
        tmp_path,
        source_parents=[parent],
    )

    assert any("outside output directory" in error for error in errors)

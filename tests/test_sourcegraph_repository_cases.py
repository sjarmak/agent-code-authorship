def test_validator_rejects_self_consistent_event_metadata_drift(
    discovery_specification: dict,
    workflow_specification: dict,
    tmp_path: Path,
):
    packet_index = _packet_index(
        discovery_specification,
        _packet(packet_id="1" * 64),
    )
    workflow = _workflow_for_index(workflow_specification, packet_index)
    manifest = build_repository_case_index(
        discovery_specification,
        workflow,
        packet_index,
        tmp_path,
    )
    changed = copy.deepcopy(manifest)
    record = changed["repositories"][0]
    case_path = tmp_path / record["case_file"]
    case = json.loads(case_path.read_text())
    event_id = case["events"][0]["event_id"]
    for event in case["events"]:
        if event["event_id"] == event_id:
            event["candidate_event"]["observed_at"] = "1999-01-01T00:00:00Z"
    for queue in case["queues"].values():
        for event in queue:
            if event["event_id"] == event_id:
                event["candidate_event"]["observed_at"] = "1999-01-01T00:00:00Z"
    case["repository_case_sha256"] = repository_case_sha256(case)
    payload = (
        json.dumps(case, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
        + "\n"
    ).encode()
    case_path.write_bytes(payload)
    record["byte_count"] = len(payload)
    record["sha256"] = hashlib.sha256(payload).hexdigest()
    changed["case_index_sha256"] = case_index_sha256(changed)

    errors = validate_repository_case_index(
        changed,
        tmp_path,
        packet_index,
        workflow,
    )

    assert "repository case differs from frozen packet evidence" in errors



def test_builder_rejects_checksum_and_packet_binding_drift(
    discovery_specification: dict,
    workflow_specification: dict,
    tmp_path: Path,
):
    packet_index = _packet_index(
        discovery_specification,
        _packet(packet_id="1" * 64),
    )
    workflow = _workflow_for_index(workflow_specification, packet_index)
    broken_workflow = copy.deepcopy(workflow)
    broken_workflow["workflow_sha256"] = "f" * 64
    with pytest.raises(RepositoryCaseError, match="workflow specification checksum"):
        build_repository_case_index(
            discovery_specification,
            broken_workflow,
            packet_index,
            tmp_path,
        )

    wrong_checksum = copy.deepcopy(workflow)
    wrong_checksum["packet_index"]["packet_index_sha256"] = "f" * 64
    wrong_checksum["workflow_sha256"] = workflow_sha256(wrong_checksum)
    with pytest.raises(RepositoryCaseError, match="packet index checksum"):
        build_repository_case_index(
            discovery_specification,
            wrong_checksum,
            packet_index,
            tmp_path,
        )

    wrong_count = copy.deepcopy(workflow)
    wrong_count["packet_index"]["packet_count"] = 2
    wrong_count["workflow_sha256"] = workflow_sha256(wrong_count)
    with pytest.raises(RepositoryCaseError, match="packet count"):
        build_repository_case_index(
            discovery_specification,
            wrong_count,
            packet_index,
            tmp_path,
        )

    tampered_index = copy.deepcopy(packet_index)
    tampered_index["packet_count"] = 2
    with pytest.raises(RepositoryCaseError, match="packet index is invalid"):
        build_repository_case_index(
            discovery_specification,
            workflow,
            tampered_index,
            tmp_path,
        )



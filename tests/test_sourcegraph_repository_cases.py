CUTOFF = "a" * 40


def _packet(
    *,
    packet_id: str,
    repository: str = "org/repo",
    commit_oid: str = "b" * 40,
    observed_at: str = "2025-01-02T00:00:00Z",
    query_family_id: str = "agent_trailer_commits",
    packet_type: str = "adoption_event",
    value: str = "Co-authored-by: Claude <noreply@anthropic.com>",
) -> dict:
    mirror = repository.replace("/", "-")
    rendered_query = (
        f"repo:^github\\.com/sg-evals/{mirror}$@{CUTOFF} "
        f"type:commit {query_family_id} count:all patternType:regexp"
    )
    packet = {
        "packet_version": 3,
        "packet_id": packet_id,
        "packet_type": packet_type,
        "canonical_repository_id": repository,
        "canonical_source_url": f"https://github.com/{repository}",
        "sourcegraph_name": f"github.com/sg-evals/{mirror}",
        "cutoff_commit": CUTOFF,
        "indexed_revision_oid": CUTOFF,
        "query_family_id": query_family_id,
        "rendered_query": rendered_query,
        "rendered_query_sha256": hashlib.sha256(rendered_query.encode()).hexdigest(),
        "sourcegraph_result_ids": [f"sha256:{packet_id}"],
        "candidate_event": {
            "commit_oid": commit_oid,
            "observed_at": observed_at,
        },
        "raw_evidence": [
            {
                "kind": "commit_message",
                "commit_oid": commit_oid,
                "path": None,
                "line": None,
                "value": value,
                "source_url": f"https://github.com/{repository}/commit/{commit_oid}",
            }
        ],
        "outcomes_consulted": False,
    }
    return {**packet, "packet_sha256": evidence_packet_sha256(packet)}


def _packet_index(specification: dict, *packets: dict) -> dict:
    ordered_packets = sorted(
        packets,
        key=lambda packet: (
            packet["candidate_event"]["observed_at"],
            packet["candidate_event"]["commit_oid"],
            packet["canonical_repository_id"],
            packet["packet_type"],
            packet["query_family_id"],
            packet["packet_id"],
        ),
    )
    document = {
        "packet_index_version": 3,
        "specification_sha256": specification["specification_sha256"],
        "source_result_manifest_sha256s": ["c" * 64],
        "packet_count": len(packets),
        "pending_file_enrichment_count": 0,
        "sourcegraph_line_number_basis": "zero_based_as_returned_by_graphql",
        "source_url_line_anchor_basis": "one_based",
        "packets": ordered_packets,
        "pending_file_enrichments": [],
        "outcomes_consulted": False,
    }
    return {**document, "packet_index_sha256": packet_index_sha256(document)}


def _workflow_for_index(workflow: dict, packet_index: dict) -> dict:
    configured = copy.deepcopy(workflow)
    configured["packet_index"]["packet_index_sha256"] = packet_index[
        "packet_index_sha256"
    ]
    configured["packet_index"]["packet_count"] = packet_index["packet_count"]
    configured["workflow_sha256"] = workflow_sha256(configured)
    return configured



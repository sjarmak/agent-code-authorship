def _load_cases(output_root: Path, manifest: dict) -> list[dict]:
    return [
        json.loads((output_root / record["case_file"]).read_text())
        for record in manifest["repositories"]
    ]


def test_builds_repository_cases_without_expanding_reviews_per_packet(
    discovery_specification: dict,
    workflow_specification: dict,
    tmp_path: Path,
    root: Path,
):
    duplicate_explicit = _packet(
        packet_id="1" * 64,
        query_family_id="agent_trailer_commits",
        commit_oid="b" * 40,
    )
    second_observation = _packet(
        packet_id="2" * 64,
        query_family_id="generated_code_disclosure_diffs",
        commit_oid="b" * 40,
        value="Generated by Claude",
    )
    announcement = _packet(
        packet_id="3" * 64,
        query_family_id="adoption_announcement_files",
        commit_oid="c" * 40,
        observed_at="2024-01-02T00:00:00Z",
        value="We are using an agent",
    )
    policy = _packet(
        packet_id="4" * 64,
        query_family_id="ai_ban_policy_introduction_diffs",
        packet_type="ai_ban_policy",
        commit_oid="d" * 40,
        value="AI-generated contributions are prohibited",
    )
    other_repository = _packet(
        packet_id="5" * 64,
        repository="other/repo",
        query_family_id="recognized_agent_identity_commits",
        commit_oid="e" * 40,
    )
    packet_index = _packet_index(
        discovery_specification,
        duplicate_explicit,
        second_observation,
        announcement,
        policy,
        other_repository,
    )
    workflow_specification = _workflow_for_index(
        workflow_specification,
        packet_index,
    )

    manifest = build_repository_case_index(
        discovery_specification,
        workflow_specification,
        packet_index,
        tmp_path,
    )
    cases = _load_cases(tmp_path, manifest)

    assert manifest["repository_count"] == 2
    assert manifest["event_count"] == 4
    assert manifest["packet_count"] == 5
    assert manifest["review_unit"] == "repository_event"
    assert manifest["packet_level_exhaustive_review_required"] is False
    assert sum(record["packet_count"] for record in manifest["repositories"]) == 5
    assert sum(record["event_count"] for record in manifest["repositories"]) == 4

    primary = next(
        case for case in cases if case["canonical_repository_id"] == "org/repo"
    )
    explicit = primary["queues"]["explicit_provenance_candidates"]
    assert len(explicit) == 1
    assert explicit[0]["packet_ids"] == ["1" * 64, "2" * 64]
    assert explicit[0]["query_family_ids"] == [
        "agent_trailer_commits",
        "generated_code_disclosure_diffs",
    ]
    assert primary["queues"]["adoption_anchor_candidates"] == explicit
    assert [
        event["query_family_ids"]
        for event in primary["queues"]["adoption_challenge_candidates"]
    ] == [["adoption_announcement_files"]]
    assert len(primary["queues"]["ai_ban_candidates"]) == 1
    assert primary["workflow"]["adoption_stop_rule"] == (
        "accept the earliest credible anchor only after resolving every "
        "earlier challenge candidate"
    )
    assert primary["workflow"]["post_adoption_implies_agent"] is False
    assert primary["workflow"]["ambiguous_case_review"] == (
        "two independent reviews plus distinct resolution"
    )

    packet_ids = sorted(
        packet_id
        for case in cases
        for event in case["events"]
        for packet_id in event["packet_ids"]
    )
    assert packet_ids == [str(index) * 64 for index in range(1, 6)]
    assert manifest["case_index_sha256"] == case_index_sha256(manifest)
    for case in cases:
        assert case["repository_case_sha256"] == repository_case_sha256(case)

    index_schema = json.loads(
        (root / "study/sourcegraph-repository-case-index.schema.json").read_text()
    )
    case_schema = json.loads(
        (root / "study/sourcegraph-repository-case.schema.json").read_text()
    )
    jsonschema.Draft202012Validator(index_schema).validate(manifest)
    validator = jsonschema.Draft202012Validator(case_schema)
    for case in cases:
        validator.validate(case)
    assert (
        validate_repository_case_index(
            manifest,
            tmp_path,
            packet_index,
            workflow_specification,
        )
        == []
    )


def test_case_order_is_deterministic_and_workflow_is_outcome_blind(
    discovery_specification: dict,
    workflow_specification: dict,
    tmp_path: Path,
):
    later = _packet(
        packet_id="1" * 64,
        observed_at="2025-02-01T00:00:00Z",
        commit_oid="b" * 40,
    )
    earlier = _packet(
        packet_id="2" * 64,
        observed_at="2024-02-01T00:00:00Z",
        commit_oid="c" * 40,
    )
    packet_index = _packet_index(discovery_specification, later, earlier)
    workflow_specification = _workflow_for_index(
        workflow_specification,
        packet_index,
    )

    first = build_repository_case_index(
        discovery_specification,
        workflow_specification,
        packet_index,
        tmp_path,
    )
    second = build_repository_case_index(
        discovery_specification,
        workflow_specification,
        packet_index,
        tmp_path,
    )

    assert second == first
    case = _load_cases(tmp_path, first)[0]
    assert [
        event["candidate_event"]["observed_at"]
        for event in case["queues"]["explicit_provenance_candidates"]
    ] == ["2024-02-01T00:00:00Z", "2025-02-01T00:00:00Z"]
    assert case["outcomes_consulted"] is False

    exposed = copy.deepcopy(packet_index)
    exposed["outcomes_consulted"] = True
    exposed["packet_index_sha256"] = packet_index_sha256(exposed)
    with pytest.raises(RepositoryCaseError, match="outcome blind"):
        build_repository_case_index(
            discovery_specification,
            workflow_specification,
            exposed,
            tmp_path,
        )



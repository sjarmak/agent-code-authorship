SHA_A = "a" * 40
SHA_B = "b" * 40
SHA_C = "c" * 40
SOURCEGRAPH_NAME = "github.com/sg-evals/org-repo"
CANONICAL_ID = "org/repo"
CANONICAL_URL = "https://github.com/org/repo"


@pytest.fixture
def specification() -> dict:
    path = Path(__file__).resolve().parents[1] / "study/sourcegraph-discovery.v3.json"
    return json.loads(path.read_text())


@pytest.fixture
def index_manifest() -> dict:
    return {
        "repositories": [
            {
                "canonical_repository_id": CANONICAL_ID,
                "canonical_source_url": CANONICAL_URL,
                "cutoff_commit": SHA_A,
            }
        ]
    }


def canonical_hash(value: object) -> str:
    payload = json.dumps(
        value, ensure_ascii=False, separators=(",", ":"), sort_keys=True
    ).encode()
    return hashlib.sha256(payload).hexdigest()


def commit_result(*, diff: bool = False) -> dict:
    return {
        "__typename": "CommitSearchResult",
        "messagePreview": {
            "value": "Generated-by: Codex",
            "highlights": [],
        },
        "diffPreview": (
            {"value": "+ generated by Codex", "highlights": []} if diff else None
        ),
        "commit": {
            "repository": {"name": SOURCEGRAPH_NAME},
            "oid": SHA_B,
            "url": f"/org-repo/-/commit/{SHA_B}",
            "subject": "Generated-by: Codex",
            "author": {
                "date": "2025-03-01T12:00:00Z",
                "person": {
                    "name": "Agent Author",
                    "email": "agent@example.com",
                    "displayName": "Agent Author",
                },
            },
            "committer": {
                "date": "2025-03-02T12:00:00Z",
                "person": {
                    "name": "Agent Committer",
                    "email": "committer@example.com",
                    "displayName": "Agent Committer",
                },
            },
        },
    }


def file_result() -> dict:
    return {
        "__typename": "FileMatch",
        "repository": {"name": SOURCEGRAPH_NAME, "url": "/org-repo"},
        "file": {
            "name": "POLICY.md",
            "path": "docs/POLICY.md",
            "url": f"/org-repo/-/blob/{SHA_A}/docs/POLICY.md",
            "commit": {"oid": SHA_A},
        },
        "lineMatches": [
            {
                "preview": "AI-generated contributions are prohibited.",
                "lineNumber": 4,
                "offsetAndLengths": [[0, 12]],
                "limitHit": False,
            },
            {
                "preview": "Do not submit LLM generated code.",
                "lineNumber": 8,
                "offsetAndLengths": [[14, 3]],
                "limitHit": False,
            },
        ],
    }


def shard(specification: dict, family_id: str, raw_results: list[dict]) -> dict:
    family = next(
        family
        for family in specification["query_families"]
        if family["id"] == family_id
    )
    query = (
        family["query_template"]
        .replace("{sourcegraph_repo_regex}", r"github\.com/sg-evals/org-repo")
        .replace("{cutoff_commit}", SHA_A)
    )
    records = [
        {
            "sourcegraph_result_id": f"sha256:{canonical_hash(raw)}",
            "payload": raw,
        }
        for raw in raw_results
    ]
    records.sort(key=lambda record: record["sourcegraph_result_id"])
    document = {
        "result_manifest_version": 3,
        "query_family_id": family_id,
        "result_type": family["result_type"],
        "canonical_repository_id": CANONICAL_ID,
        "sourcegraph_name": SOURCEGRAPH_NAME,
        "cutoff_commit": SHA_A,
        "rendered_query": query,
        "rendered_query_sha256": hashlib.sha256(query.encode()).hexdigest(),
        "unit_id": "d" * 64,
        "executed_at": "2026-07-27T20:45:00Z",
        "sourcegraph_result_ids": [
            record["sourcegraph_result_id"] for record in records
        ],
        "result_count": len(records),
        "result_object_count": len(records),
        "limit_hit": False,
        "cloning_repositories": [],
        "missing_repositories": [],
        "timed_out_repositories": [],
        "valid": True,
        "invalid_reasons": [],
        "raw_results": records,
        "outcomes_consulted": False,
    }
    return {
        **document,
        "result_manifest_sha256": result_manifest_sha256(document),
    }


def file_enrichment(result_shard: dict) -> dict:
    result_id = result_shard["sourcegraph_result_ids"][0]
    return {
        "result_manifest_sha256": result_shard["result_manifest_sha256"],
        "sourcegraph_result_id": result_id,
        "indexed_revision_oid": SHA_A,
        "default_branch_reachable": True,
        "lines": [
            {
                "line": 4,
                "commit_oid": SHA_B,
                "observed_at": "2025-04-01T00:00:00Z",
            },
            {
                "line": 8,
                "commit_oid": SHA_C,
                "observed_at": "2025-05-01T00:00:00Z",
            },
        ],
    }


@pytest.mark.parametrize(
    ("family_id", "expected_kind"),
    [
        ("agent_trailer_commits", "commit_message"),
        ("recognized_agent_identity_commits", "commit_identity"),
        ("generated_code_disclosure_diffs", "diff_added"),
        ("ai_ban_policy_introduction_diffs", "diff_added"),
    ],
)
def test_commit_and_diff_results_become_raw_fact_packets(
    specification: dict,
    index_manifest: dict,
    family_id: str,
    expected_kind: str,
):
    result_shard = shard(
        specification,
        family_id,
        [commit_result(diff=family_id.endswith("_diffs"))],
    )

    packet_index = build_packet_index(
        specification,
        index_manifest,
        [result_shard],
        file_blame_enrichments=[],
    )

    assert packet_index["packet_count"] == 1
    assert packet_index["pending_file_enrichment_count"] == 0
    packet = packet_index["packets"][0]
    assert packet["raw_evidence"][0]["kind"] == expected_kind
    assert packet["candidate_event"] == {
        "commit_oid": SHA_B,
        "observed_at": "2025-03-02T12:00:00Z",
    }
    assert packet["packet_sha256"] == evidence_packet_sha256(packet)
    assert validate_evidence_packet(packet, specification) == []
    assert not ({"decision", "adoption_status", "policy_status"} & packet.keys())


def test_file_results_require_blame_and_split_by_introducing_commit(
    specification: dict,
    index_manifest: dict,
):
    result_shard = shard(specification, "ai_ban_policy_files", [file_result()])

    pending = build_packet_index(
        specification,
        index_manifest,
        [result_shard],
        file_blame_enrichments=[],
    )
    complete = build_packet_index(
        specification,
        index_manifest,
        [result_shard],
        file_blame_enrichments=[file_enrichment(result_shard)],
    )

    assert pending["packet_count"] == 0
    assert pending["pending_file_enrichment_count"] == 1
    assert complete["packet_count"] == 2
    assert complete["pending_file_enrichment_count"] == 0
    assert [
        packet["candidate_event"]["commit_oid"] for packet in complete["packets"]
    ] == [SHA_B, SHA_C]
    for packet in complete["packets"]:
        assert [evidence["kind"] for evidence in packet["raw_evidence"]] == [
            "file_content",
            "blame",
        ]
        assert validate_evidence_packet(packet, specification) == []



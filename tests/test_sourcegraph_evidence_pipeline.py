def test_invalid_or_unbound_inputs_fail_closed(
    specification: dict,
    index_manifest: dict,
):
    invalid = shard(specification, "agent_trailer_commits", [commit_result()])
    invalid["valid"] = False
    invalid["invalid_reasons"] = ["limit_hit_requires_partition"]
    invalid["limit_hit"] = True
    invalid["result_manifest_sha256"] = result_manifest_sha256(invalid)

    with pytest.raises(EvidencePipelineError, match="invalid query result"):
        build_packet_index(
            specification,
            index_manifest,
            [invalid],
            file_blame_enrichments=[],
        )
    unknown = copy.deepcopy(index_manifest)
    unknown["repositories"] = []
    with pytest.raises(EvidencePipelineError, match="canonical repository"):
        build_packet_index(
            specification,
            unknown,
            [shard(specification, "agent_trailer_commits", [commit_result()])],
            file_blame_enrichments=[],
        )


def test_packet_index_is_deterministic_deduplicated_and_checksummed(
    specification: dict,
    index_manifest: dict,
):
    first_shard = shard(
        specification, "agent_trailer_commits", [commit_result(), commit_result()]
    )
    second_shard = shard(
        specification, "generated_code_disclosure_diffs", [commit_result(diff=True)]
    )

    first = build_packet_index(
        specification,
        index_manifest,
        [second_shard, first_shard],
        file_blame_enrichments=[],
    )
    second = build_packet_index(
        specification,
        index_manifest,
        [first_shard, second_shard],
        file_blame_enrichments=[],
    )

    assert first == second
    assert first["packet_count"] == 2
    assert first["packet_index_sha256"] == packet_index_sha256(first)
    assert validate_packet_index(first, specification) == []
    packet_ids = [packet["packet_id"] for packet in first["packets"]]
    assert len(packet_ids) == len(set(packet_ids))


def test_overlapping_partition_queries_deduplicate_same_result_provenance(
    specification: dict,
    index_manifest: dict,
):
    first_shard = shard(specification, "agent_trailer_commits", [commit_result()])
    overlap_shard = copy.deepcopy(first_shard)
    overlap_shard["rendered_query"] += ' after:"2025-01-01"'
    overlap_shard["rendered_query_sha256"] = hashlib.sha256(
        overlap_shard["rendered_query"].encode()
    ).hexdigest()
    overlap_shard["unit_id"] = discovery_unit_id(overlap_shard)
    overlap_shard["result_manifest_sha256"] = result_manifest_sha256(overlap_shard)

    packet_index = build_packet_index(
        specification,
        index_manifest,
        [overlap_shard, first_shard],
        file_blame_enrichments=[],
    )

    assert packet_index["packet_count"] == 1
    assert packet_index["source_result_manifest_sha256s"] == sorted(
        [
            first_shard["result_manifest_sha256"],
            overlap_shard["result_manifest_sha256"],
        ]
    )
    assert packet_index["packets"][0]["rendered_query_sha256"] == min(
        first_shard["rendered_query_sha256"],
        overlap_shard["rendered_query_sha256"],
    )



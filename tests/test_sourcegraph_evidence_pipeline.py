def test_packet_index_and_packets_match_schemas(
    specification: dict,
    index_manifest: dict,
):
    root = Path(__file__).resolve().parents[1]
    result_shard = shard(specification, "ai_ban_policy_files", [file_result()])
    packet_index = build_packet_index(
        specification,
        index_manifest,
        [result_shard],
        file_blame_enrichments=[file_enrichment(result_shard)],
    )
    packet_schema = json.loads(
        (root / "study/sourcegraph-evidence-packet.schema.json").read_text()
    )
    index_schema = json.loads(
        (root / "study/sourcegraph-evidence-packet-index.schema.json").read_text()
    )

    jsonschema.Draft202012Validator(index_schema).validate(packet_index)
    for packet in packet_index["packets"]:
        jsonschema.Draft202012Validator(packet_schema).validate(packet)


